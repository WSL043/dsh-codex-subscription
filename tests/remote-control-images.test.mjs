test('a real local image reference is transported inline; text disguised as PNG and files outside the conversation stay unread', async () => {
  const root = await mkdtemp(join(tmpdir(), 'phone-image-'))
  const outside = await mkdtemp(join(tmpdir(), 'phone-private-'))
  try {
    await writeFile(join(root, 'whale.png'), png)
    await writeFile(join(root, 'log.png'), 'not an image')
    await writeFile(join(outside, 'private.png'), png)
    for (const ref of ['whale.png', `<${join(root, 'whale.png')}>`]) {
      const shown = await phoneImageMarkdown(`Before\n![Whale](${ref})\nAfter`, root)
      assert.match(shown, /Before\n!\[Whale\]\(data:image\/png;base64,/)
      assert.ok(shown.endsWith('\nAfter'))
    }
    for (const ref of ['log.png', join(outside, 'private.png'), 'https://example.org/image.png']) {
      const original = `![Picture](${ref})`
      assert.equal(await phoneImageMarkdown(original, root), original)
    }
  } finally { await rm(root, { recursive: true, force: true }); await rm(outside, { recursive: true, force: true }) }
})

test('a missing historical sketch preview uses the finished attachment, with no drawing-tool changes', () => {
  const url = `data:image/png;base64,${png.toString('base64')}`
  const tool = { type: 'dynamicToolCall', tool: 'codex_sketch', arguments: { action: 'finish' }, success: true, contentItems: [{ type: 'inputImage', imageUrl: url }] }
  const shown = withGeneratedImageOutput({ id: 'old', items: [tool, { type: 'agentMessage', id: 'answer', text: 'Done\n![Whale](C:/missing/whale_maid_sketch.png)' }] })
  assert.equal(shown.items[1].text, `Done\n![Whale](${url})`)
  assert.equal(shown.items[0], tool)
  const preview = { ...tool, arguments: { action: 'preview' } }
  const original = { id: 'preview', items: [preview] }
  assert.equal(withGeneratedImageOutput(original), original)
})

test('historical finish without an attachment reuses only a full preview of the same document revision', () => {
  const url = `data:image/png;base64,${png.toString('base64')}`
  const content = revision => [{ type: 'inputText', text: JSON.stringify({ documentId: 'drawing', revision }) }]
  const preview = { type: 'dynamicToolCall', tool: 'codex_sketch', arguments: { action: 'preview' }, success: true, contentItems: [...content(27), { type: 'inputImage', imageUrl: url }] }
  const finish = { ...preview, arguments: { action: 'finish' }, contentItems: content(27) }
  const turn = { id: 'old', items: [preview, finish, { type: 'agentMessage', id: 'answer', text: '![Drawing](missing.png)' }] }
  assert.equal(withGeneratedImageOutput(turn).items.at(-1).text, `![Drawing](${url})`)
  for (const changed of [{ ...preview, contentItems: [...content(26), { type: 'inputImage', imageUrl: url }] }, { ...preview, arguments: { action: 'preview', mode: 'side' } }]) {
    const mismatched = { ...turn, items: [changed, finish, turn.items.at(-1)] }
    assert.equal(withGeneratedImageOutput(mismatched), mismatched)
  }
})
