test('a final-answer image has an app-server readable path without exposing other host files', () => {
  const files = createPhoneImageFiles(), url = `data:image/png;base64,${png.toString('base64')}`
  const path = files.publish(url)
  assert.match(path, /\/dsh\/phone-images\/[a-f0-9]{64}\.png$/u)
  assert.equal(files.publish(url), path)
  assert.deepEqual(Buffer.from(files.read(path).dataBase64, 'base64'), png)
  assert.equal(files.read(path + '/../private.txt'), undefined)
  assert.equal(files.read('C:/Users/private/.credentials.yaml'), undefined)
  assert.equal(files.read('/etc/passwd'), undefined)
  const turn = { id: 't', items: [{ type: 'imageGeneration', status: 'completed', result: png.toString('base64') }, { type: 'agentMessage', text: 'Done' }] }
  const shown = withGeneratedImageOutput(turn, files.publish)
  assert.equal(shown.items[1].text, `Done\n\n![Image](${path})`)
  assert.equal(withGeneratedImageOutput(shown, files.publish), shown)
})

test('history restoration exposes the exact generated bytes through the advertised image-only file reader', async () => {
  const ref = { attachmentId: 'picture', mediaType: 'image/png' }
  const messages = [
    { role: 'user', id: 'u', source: { kind: 'user' }, content: [{ type: 'text', text: 'draw' }] },
    { role: 'assistant', id: 'a', content: [{ type: 'tool-call', name: 'codex_image_generate', id: 'tool', arguments: '{}' }] },
    { role: 'tool', toolCallId: 'tool', content: [{ type: 'image', attachment: ref }] },
    { role: 'assistant', id: 'done', content: [{ type: 'text', text: 'Done' }] },
  ]
  const session = { id: 's', meta: {}, deriveMessages: () => messages }
  const bridge = createDshRemoteControl({ controller: () => ({ resolveAgent: async () => ({ agent: { session } }), modelCatalog: async () => ({ groups: [] }) }), agents: () => ({}), attachments: () => ({ readImage: async () => ({ ref, data: png }) }), userAgent: 'test/1' })
  const result = await bridge.methods['thread/resume']({ threadId: 's' }, { notify: async () => {} })
  const text = result.thread.turns[0].items.at(-1).text
  assert.doesNotMatch(text, /data:image/u)
  const path = /!\[Image\]\(([^)]+)\)/u.exec(text)[1]
  assert.equal(bridge.methods['fs/getMetadata']({ path }).isFile, true)
  assert.deepEqual(Buffer.from(bridge.methods['fs/readFile']({ path }).dataBase64, 'base64'), png)
  assert.throws(() => bridge.methods['fs/readFile']({ path: '../private.txt' }), /Only conversation images/u)
})

